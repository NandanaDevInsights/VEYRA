define('DB_PASSWORD', getenv('DB_PASSWORD') !== false ? getenv('DB_PASSWORD') : '');
define('DB_NAME', getenv('DB_NAME') ?: 'VEYRA');
define('PORT', (int)(getenv('PORT') ?: 5000));
